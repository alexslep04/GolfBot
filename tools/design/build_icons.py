"""Convert exported SF Symbol PDFs into web/icons.js.

Usage: build_icons.py <pdf_dir> <out.js>   (needs `mutool` on PATH)

Each symbol becomes {b: glyph bounds [x, y, w, h]} plus either d (one path) or
l (ordered layers). SF Symbols draw inner details (the lines in a speech
bubble, the pips on dice) as luminance masks over the artwork; each mask
becomes a cut-out layer that the web client paints in the outline colour.
"""
import json
import pathlib
import re
import subprocess
import sys
import xml.etree.ElementTree as ET

SVG = '{http://www.w3.org/2000/svg}'
pdf_dir, out = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])


def convert(matrix, data, xs, ys):
    """Bake mutool's flip-and-translate matrix into absolute path coordinates."""
    a, b, c, d, e, f = (float(x) for x in matrix)
    assert (a, b, c, d) == (1, 0, 0, -1), matrix
    parts, cmd, coords = [], None, []

    def flush():
        if cmd is None:
            return
        if cmd in 'Zz':
            parts.append('Z')
            return
        if cmd == 'H':
            vals = [round(coords[0] + e, 2)]
            xs.append(vals[0])
        elif cmd == 'V':
            vals = [round(f - coords[0], 2)]
            ys.append(vals[0])
        else:
            vals = []
            for i in range(0, len(coords), 2):
                vals += [round(coords[i] + e, 2), round(f - coords[i + 1], 2)]
                xs.append(vals[-2])
                ys.append(vals[-1])
        parts.append(cmd + ' '.join(f'{v:g}' for v in vals))

    for token in re.findall(r'[A-Za-z]|-?[\d.]+(?:e-?\d+)?', data):
        if token.isalpha():
            flush()
            cmd, coords = token, []
        else:
            coords.append(float(token))
    flush()
    return ''.join(parts)


def paths_in(node, in_clip=False):
    """Every drawn path under a node, skipping clip-path definitions."""
    tag = node.tag.replace(SVG, '')
    if tag == 'clipPath':
        return
    if tag == 'path':
        yield node
    for child in node:
        yield from paths_in(child)


def matrix_of(node):
    return re.match(r'matrix\(([^)]*)\)', node.get('transform', 'matrix(1,0,0,-1,0,0)'))[1].split(',')


icons = {}
for pdf in sorted(pdf_dir.glob('*.pdf')):
    svg = subprocess.run(['mutool', 'draw', '-F', 'svg', '-o', '-', str(pdf)], capture_output=True, text=True).stdout
    root = ET.fromstring(svg)
    masks = {node.get('id').replace('_contents', ''): node for node in root.iter(SVG + 'g')
             if (node.get('id') or '').endswith('_contents')}
    layers, xs, ys = [], [], []  # ordered [is_cut, path]

    def body(node):
        for path in paths_in(node):
            layers.append([0, convert(matrix_of(path), path.get('d'), xs, ys)])

    def draw(node):
        tag = node.tag.replace(SVG, '')
        if tag == 'defs':
            return
        mask = re.match(r'url\(#(.+)\)', node.get('mask') or '')
        if tag == 'path':
            body(node)
        elif mask:
            # the masked artwork first, then whatever its mask blacks out
            for child in node:
                if child.get('mask'):
                    continue
                body(child)
            for path in paths_in(masks[mask[1]]):
                layers.append([1, convert(matrix_of(path), path.get('d'), [], [])])
            for child in node:
                if child.get('mask'):
                    draw(child)
        else:
            for child in node:
                draw(child)

    draw(root)
    if not xs:
        print('skip', pdf.name)
        continue
    # merge neighbouring layers of the same kind to keep the file small
    merged = []
    for kind, data in layers:
        if merged and merged[-1][0] == kind:
            merged[-1][1] += ' ' + data
        else:
            merged.append([kind, data])
    entry = {'b': [round(min(xs), 1), round(min(ys), 1), round(max(xs) - min(xs), 1), round(max(ys) - min(ys), 1)]}
    if len(merged) == 1:
        entry['d'] = merged[0][1]
    else:
        entry['l'] = merged
    icons[pdf.stem] = entry

out.write_text('"use strict";\n// Generated by tools/design/build_icons.py from SF Symbols (bold, rounded, 100pt).\n'
               '// b = glyph bounds [x, y, w, h]; d = single path; l = ordered layers [isCutOut, path].\n'
               'const ICONS = ' + json.dumps(icons, separators=(',', ':')) + ';\n')
print(len(icons), 'icons,', sum('l' in icon for icon in icons.values()), 'layered,', out.stat().st_size, 'bytes')
